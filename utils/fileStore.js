const fs = require('fs/promises');
const path = require('path');

const { customQuery } = require('./dbFunctions');

// Where uploaded files live. Callers only use put / get / remove with a storage key, so the place
// can change without changing them; each stored row records its driver.
//   FILE_STORE=db : in the database (table dbo.FileBlobs), for hosts without a lasting disk (Render).
//                   Until that table exists, files go to the folder below, so nothing breaks.
//   otherwise     : a folder on the server (UPLOAD_DIR, default ./uploads).
// Reading looks in the database first (when FILE_STORE=db), then in the folder, so files saved
// before the switch still open. A cloud bucket can be added later as a third driver.

const ROOT = path.resolve(process.env.UPLOAD_DIR || path.join(__dirname, '..', 'uploads'));
const USE_DB = String(process.env.FILE_STORE || '').toLowerCase() === 'db';
const DRIVER = USE_DB ? 'db' : 'local';

const noTable = (error) => /Invalid object name 'dbo\.FileBlobs'/i.test(error?.message || '');

// Keys are generated by the server ("doctor-evidence/<doctorId>/<uuid>.jpg"); never trust a client path.
const resolveKey = (key) => {
    const full = path.resolve(ROOT, key);
    if (!full.startsWith(ROOT + path.sep)) throw new Error('Invalid storage key.');
    return full;
};

const SQL = {
    put: `
        UPDATE dbo.FileBlobs SET Data = @Data, SizeBytes = @SizeBytes, CreatedOn = @Now WHERE StorageKey = @StorageKey;
        IF @@ROWCOUNT = 0
            INSERT INTO dbo.FileBlobs (StorageKey, Data, SizeBytes, CreatedOn) VALUES (@StorageKey, @Data, @SizeBytes, @Now);`,
    get: `SELECT Data FROM dbo.FileBlobs WHERE StorageKey = @StorageKey`,
    remove: `DELETE FROM dbo.FileBlobs WHERE StorageKey = @StorageKey`,
};

const putLocal = async (key, buffer) => {
    const full = resolveKey(key);
    await fs.mkdir(path.dirname(full), { recursive: true });
    await fs.writeFile(full, buffer);
    return { driver: 'local', key };
};

const put = async (key, buffer) => {
    resolveKey(key); // same key rules for every driver
    if (USE_DB) {
        try {
            await customQuery(SQL.put, { StorageKey: key, Data: buffer, SizeBytes: buffer.length, Now: new Date() });
            return { driver: 'db', key };
        } catch (error) {
            if (!noTable(error)) throw error;
            console.warn('dbo.FileBlobs does not exist yet: saving the file to the folder instead.');
        }
    }
    return putLocal(key, buffer);
};

const get = async (key) => {
    const full = resolveKey(key);
    if (USE_DB) {
        try {
            const [row] = await customQuery(SQL.get, { StorageKey: key });
            if (row?.Data) return Buffer.from(row.Data);
        } catch (error) {
            if (!noTable(error)) throw error;
        }
    }
    return fs.readFile(full);
};

const remove = async (key) => {
    const full = resolveKey(key);
    if (USE_DB) {
        try {
            await customQuery(SQL.remove, { StorageKey: key });
        } catch (error) {
            if (!noTable(error)) throw error;
        }
    }
    try {
        await fs.unlink(full);
    } catch (error) {
        if (error.code !== 'ENOENT') throw error;
    }
};

// Recognises the image types we accept from the file's first bytes, not from what the client claims.
const sniffImage = (buffer) => {
    if (!buffer || buffer.length < 12) return null;
    if (buffer[0] === 0xff && buffer[1] === 0xd8 && buffer[2] === 0xff) return { contentType: 'image/jpeg', ext: 'jpg' };
    if (buffer.slice(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]))) return { contentType: 'image/png', ext: 'png' };
    if (buffer.slice(0, 4).toString('ascii') === 'RIFF' && buffer.slice(8, 12).toString('ascii') === 'WEBP') return { contentType: 'image/webp', ext: 'webp' };
    return null;
};

module.exports = { put, get, remove, sniffImage, DRIVER };
